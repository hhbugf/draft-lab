// Keep readable source in dist/*.js; publish transpiled modules for older webviews.
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {transform} from 'esbuild';
const dist=fileURLToPath(new URL('../dist/',import.meta.url));
const modules=['engine','discovery','analytics','insights','discovery-ui','mobile','app'];
await fs.mkdir(path.join(dist,'compat'),{recursive:true});
for(const name of modules){
 const source=await fs.readFile(path.join(dist,name+'.js'),'utf8');
 const result=await transform(source,{target:'es2017',charset:'utf8',legalComments:'none',sourcefile:name+'.js'});
 await fs.writeFile(path.join(dist,'compat',name+'.js'),'/* Generated by scripts/build-browser.mjs; ES2017 syntax. */\n'+result.code);
}
console.log('Compiled '+modules.length+' browser modules to ES2017; no external runtime dependency.');
